"""Static Anno 117 game data and the derived production/progression model.

The raw data (data/game_data.json) is generated by tools/gen_data.py from the community
calculator's params.js, which is exported from the game's assets. GUIDs in it are the real
asset GUIDs, which is what the in-game mod uses to unlock and relock buildings.

ID scheme (shared with the in-game Lua bridge, which decodes IDs arithmetically):
    item 117_000_000 + GUID     unlock a building or residence (GUID of the asset)
    item 117_900_001            Denarii Cache (filler)
    loc  118_000_000 + tier GUID * 100 + threshold index    population milestone
    loc  119_000_000 + building GUID                         first construction of a building
"""
from __future__ import annotations

import json
import pkgutil
from dataclasses import dataclass

GAME_NAME = "Anno 117"
WORLD_VERSION = "0.3.3"
BRIDGE_PROTOCOL = 1

ITEM_BASE = 117_000_000
FILLER_ITEM_ID = 117_900_001
POP_LOCATION_BASE = 118_000_000
BUILD_LOCATION_BASE = 119_000_000

FILLER_ITEM_NAME = "Denarii Cache"
VICTORY_ITEM_NAME = "Victory"
GOAL_LOCATION_NAME = "Pax Romana"

# Population thresholds a milestone can use. The Lua bridge has the same table; the index is part
# of the location ID, so only ever append to this tuple.
THRESHOLDS: tuple[int, ...] = (10, 25, 50, 75, 100, 150, 200, 250, 300, 400, 500, 600, 750, 1000, 1250,
                               1500, 2000, 2500, 3000, 4000, 5000, 7500, 10000)
# Milestones at or below this only need the tier to exist. Up to ESTABLISHED_SHARE of the tier's cap they need
# one good per needs category (what upgrading needs); above that every good that adds residents.
SMALL_MILESTONE = 25
# tier index the first province needs before the game lets you into the second one
PROVINCE_ACCESS_TIER = 3
ESTABLISHED_SHARE = 0.5
NEED_CATEGORIES = ("Food", "Fashion", "Household", "Culture")
# Higher tiers have fewer residents, so their milestone caps are scaled down.
TIER_CAP_FACTOR = {1: 1.0, 2: 1.0, 3: 0.6, 4: 0.4}

REGION_LATIUM = "Roman"
REGION_ALBION = "Celtic"
PROVINCE_NAMES = {REGION_LATIUM: "Latium", REGION_ALBION: "Albion"}

DLC_PROPHECIES_OF_ASH = 67902
MILITARY_CATEGORY = "Military"

_RAW = json.loads(pkgutil.get_data(__name__, "data/game_data.json").decode("utf-8"))
DENARII_GUID: int = _RAW["denarii_guid"]
PRODUCT_NAMES: dict[int, str] = {int(g): p["name"] for g, p in _RAW["products"].items()}
CONSTRUCTION_PRODUCTS: frozenset[int] = frozenset(
    int(g) for g, p in _RAW["products"].items() if p["construction"]
)


@dataclass(frozen=True)
class Building:
    guid: int
    base_name: str
    name: str  # unique display name, e.g. "Bakery (Latium)"
    region: str
    province: str
    category: str
    workforce: int
    tier: int  # GUID of the population tier that supplies the workforce
    inputs: frozenset[int]
    outputs: frozenset[int]
    dlc: tuple[int, ...]

    @property
    def military(self) -> bool:
        return self.category == MILITARY_CATEGORY

    @property
    def item_id(self) -> int:
        return ITEM_BASE + self.guid

    @property
    def location_name(self) -> str:
        return f"Build: {self.name}"

    @property
    def location_id(self) -> int:
        return BUILD_LOCATION_BASE + self.guid


@dataclass(frozen=True)
class Need:
    name: str
    product: int | None
    category: str
    building: bool
    attrs: tuple[str, ...]
    requires_item: int | None
    dlc: tuple[int, ...]


@dataclass(frozen=True)
class Tier:
    guid: int
    name: str
    region: str
    province: str
    index: int
    parent: int | None
    workforce: int
    residence: int
    residence_name: str
    needs: tuple[Need, ...]

    @property
    def upgrade_item_name(self) -> str:
        return self.residence_name

    @property
    def upgrade_item_id(self) -> int:
        return ITEM_BASE + self.residence

    def milestone_name(self, value: int) -> str:
        return f"Population: {value} {self.name}"

    def milestone_id(self, threshold_index: int) -> int:
        return POP_LOCATION_BASE + self.guid * 100 + threshold_index


BUILDINGS: dict[int, Building] = {}
TIERS: dict[int, Tier] = {}
_WORKFORCE_TIER: dict[int, int] = {}

for _t in _RAW["tiers"]:
    TIERS[_t["guid"]] = Tier(
        guid=_t["guid"], name=_t["name"], region=_t["region"], province=_t["province"], index=_t["index"],
        parent=_t["parent"], workforce=_t["workforce"], residence=_t["residence"],
        residence_name=_t["residence_name"],
        needs=tuple(Need(n["name"], n["product"], n["category"], n["building"], tuple(n["attrs"]),
                         n["requires_item"], tuple(n["dlc"])) for n in _t["needs"]),
    )
    _WORKFORCE_TIER[_t["workforce"]] = _t["guid"]

for _f in _RAW["factories"]:
    BUILDINGS[_f["guid"]] = Building(
        guid=_f["guid"], base_name=_f["name"], name=f"{_f['name']} ({_f['province']})", region=_f["region"],
        province=_f["province"], category=_f["category"], workforce=_f["workforce"],
        tier=_WORKFORCE_TIER[_f["workforce"]], inputs=frozenset(_f["inputs"]), outputs=frozenset(_f["outputs"]),
        dlc=tuple(_f["dlc"]),
    )

assert len({b.name for b in BUILDINGS.values()}) == len(BUILDINGS), "building display names must be unique"
assert not set(b.guid for b in BUILDINGS.values()) & set(t.residence for t in TIERS.values())


def tiers_in(region: str) -> list[Tier]:
    return sorted((t for t in TIERS.values() if t.region == region), key=lambda t: (t.index, t.guid))


def base_tier(region: str) -> Tier:
    return next(t for t in tiers_in(region) if t.parent is None)


def ancestors_or_self(tier: Tier) -> tuple[int, ...]:
    chain = [tier.guid]
    while TIERS[chain[-1]].parent is not None:
        chain.append(TIERS[chain[-1]].parent)
    return tuple(chain)


def _native_products(region: str) -> frozenset[int]:
    """Products a province can make on its own with base-game buildings."""
    return frozenset(p for b in BUILDINGS.values() if b.region == region and not b.dlc for p in b.outputs)


NATIVE_PRODUCTS: dict[str, frozenset[int]] = {r: _native_products(r) for r in PROVINCE_NAMES}


def _core_products(tier: Tier) -> frozenset[int]:
    """Goods a tier must have to grow: needs that add residents, made in its own province.

    Needs that come from public buildings, need a special item, are DLC-only, or can only be made in
    the other province are treated as optional bonuses.
    """
    native = NATIVE_PRODUCTS[tier.region]
    return frozenset(
        n.product for n in tier.needs
        if not n.building and "Population" in n.attrs and n.requires_item is None and not n.dlc
        and n.product in native
    )


def _construction_products(tier: Tier) -> frozenset[int]:
    """Building materials of this tier's branch (ship/military goods excluded)."""
    branch = set(ancestors_or_self(tier))
    return frozenset(
        p for b in BUILDINGS.values()
        if b.region == tier.region and not b.dlc and not b.military and b.tier in branch
        for p in b.outputs if p in CONSTRUCTION_PRODUCTS
    )


def _category_products(tier: Tier) -> dict[str, frozenset[int]]:
    """Per needs category, the goods of which the tier needs at least one before it can upgrade.

    The game asks for the minimum of every needs category (devblog). Need lists are cumulative, so to stay on
    the safe side a tier needs one of the goods it introduces, when its own province can make one; otherwise
    any of its goods in that category. Public services come from public buildings, which keep their unlocks.
    """
    native = NATIVE_PRODUCTS[tier.region]
    parent_goods: set[int] = set()
    if tier.parent is not None:
        parent_goods = {n.product for n in TIERS[tier.parent].needs if n.requires_item is None}
    found: dict[str, set[int]] = {}
    for n in tier.needs:
        if n.category in NEED_CATEGORIES and not n.building and n.requires_item is None and not n.dlc \
                and n.product in native:
            found.setdefault(n.category, set()).add(n.product)
    result = {}
    for category, goods in found.items():
        new = goods - parent_goods
        result[category] = frozenset(new or goods)
    return result


CORE_PRODUCTS: dict[int, frozenset[int]] = {g: _core_products(t) for g, t in TIERS.items()}
CATEGORY_PRODUCTS: dict[int, dict[str, frozenset[int]]] = {g: _category_products(t) for g, t in TIERS.items()}
TIER_CONSTRUCTION: dict[int, frozenset[int]] = {g: _construction_products(t) for g, t in TIERS.items()}


def _unlock_gates() -> dict[int, frozenset[int]]:
    """For each building, the tiers at which the game would normally offer it: the earliest tier of its own
    province that uses what it makes, directly or further down the chain (oysters only matter once a tier
    wants them). Provinces are separate: Albion wanting a good early says nothing about Latium.

    Logic also waits for that tier, so a building check never depends on the game's own unlock schedule.
    Buildings whose goods no tier of their province uses get no gate. Albion's branches can tie.
    """
    gate: dict[tuple[str, int], tuple[int, frozenset[int]]] = {}  # (region, product) -> (tier index, tiers)

    def merge(key: tuple[str, int], index: int, tiers: frozenset[int]) -> bool:
        old = gate.get(key)
        if old is None or index < old[0]:
            gate[key] = (index, tiers)
            return True
        if index == old[0] and not tiers <= old[1]:
            gate[key] = (index, old[1] | tiers)
            return True
        return False

    def downstream_of(b: Building) -> tuple[int, frozenset[int]] | None:
        found = [gate[(b.region, p)] for p in b.outputs if (b.region, p) in gate]
        if not found:
            return None
        index = min(d[0] for d in found)
        return index, frozenset().union(*(d[1] for d in found if d[0] == index))

    for t in TIERS.values():
        used = {n.product for n in t.needs if n.product is not None} | set(TIER_CONSTRUCTION[t.guid])
        for p in used:
            merge((t.region, p), t.index, frozenset({t.guid}))
    changed = True
    while changed:
        changed = False
        for b in BUILDINGS.values():
            found = downstream_of(b)
            if found:
                for p in b.inputs:
                    changed |= merge((b.region, p), *found)
    result = {}
    for b in BUILDINGS.values():
        found = downstream_of(b)
        if found:
            result[b.guid] = found[1]
    return result


UNLOCK_GATES: dict[int, frozenset[int]] = _unlock_gates()

def unlock_rank(b: Building) -> int:
    """The tier index from which a building makes sense: the later of the tier that works it and the tier
    that would normally unlock it (UNLOCK_GATES)."""
    gate = UNLOCK_GATES.get(b.guid)
    return max(TIERS[b.tier].index, min(TIERS[g].index for g in gate) if gate else 0)


# Progression phases for Tiered Placement. Tiers 1-2 of both provinces (Liberti, Plebeians, Waders, Smiths,
# Mercators) are early, tier 3 (Equites, Aldermen, Nobles) is the middle game, Patricians the late game.
EARLY, MIDDLE, LATE = 1, 2, 3
PHASE_NAMES = {EARLY: "early", MIDDLE: "middle", LATE: "late"}
_PHASE_BY_TIER_INDEX = {1: EARLY, 2: EARLY, 3: MIDDLE, 4: LATE}
# Building-material chains go with the phase that builds with them, whatever tier works them.
PHASE_BY_BUILDING_NAME = {
    "Tiler": EARLY, "Labourer's Yard": EARLY, "Charcoal Burner": EARLY, "Clay Pit": EARLY, "Mud Drier": EARLY,
    "Concrete Mixer": MIDDLE, "Limestone Quarry": MIDDLE, "Granite Quarry": MIDDLE, "Granite Cutter": MIDDLE,
    "Marble Quarry": MIDDLE, "Marble Mason": MIDDLE,
    "Tessera Works": LATE,
}


def tier_phase(tier: Tier) -> int:
    return _PHASE_BY_TIER_INDEX.get(tier.index, LATE)


def building_phase(b: Building) -> int:
    override = PHASE_BY_BUILDING_NAME.get(b.base_name)
    if override is not None:
        return override
    return _PHASE_BY_TIER_INDEX.get(unlock_rank(b), LATE)


# Buildings logic never relies on: they need deposits that may not exist on the islands you can reach
# (Prophecies of Ash coal mines). They stay items you can use, but no check is placed on building them and
# logic gets coal from Charcoal Burners only.
UNRELIABLE_BUILDINGS: frozenset[int] = frozenset(
    b.guid for b in BUILDINGS.values() if b.base_name == "Coal Mine" and b.dlc
)


def _starter_buildings(region: str) -> frozenset[int]:
    """Buildings that stay vanilla: the base tier's food, income and building-material chains."""
    base = base_tier(region)
    native = NATIVE_PRODUCTS[region]
    wanted = set(CORE_PRODUCTS[base.guid]) | set(TIER_CONSTRUCTION[base.guid])
    wanted |= {
        n.product for n in base.needs
        if not n.building and "Money" in n.attrs and n.requires_item is None and not n.dlc and n.product in native
    }
    chosen: set[int] = set()
    todo = list(wanted)
    seen: set[int] = set()
    while todo:
        product = todo.pop()
        if product in seen:
            continue
        seen.add(product)
        for b in BUILDINGS.values():
            if b.region == region and not b.dlc and b.tier == base.guid and product in b.outputs:
                chosen.add(b.guid)
                todo.extend(b.inputs)
    return frozenset(chosen)


STARTER_BUILDINGS: dict[str, frozenset[int]] = {r: _starter_buildings(r) for r in PROVINCE_NAMES}


def tier_cap(tier: Tier, cap: int) -> int:
    return max(THRESHOLDS[0], int(cap * TIER_CAP_FACTOR.get(tier.index, 0.4)))


def milestone_thresholds(tier: Tier, count: int, cap: int) -> list[tuple[int, int]]:
    """(threshold index, value) pairs for a tier, evenly spread up to its scaled cap."""
    if count <= 0:
        return []
    tier_cap_value = tier_cap(tier, cap)
    candidates = [(i, v) for i, v in enumerate(THRESHOLDS) if v <= tier_cap_value]
    if len(candidates) <= count:
        return candidates
    if count == 1:
        return [candidates[-1]]
    picks = sorted({round(k * (len(candidates) - 1) / (count - 1)) for k in range(count)})
    return [candidates[p] for p in picks]
